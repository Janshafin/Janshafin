#!/usr/bin/env python3
"""Render 'Proof of work': one mark per day from Jan Shafin's public GitHub contribution calendar.

Runs in GitHub Actions with the standard library only. Text is pre-outlined in
scripts/glyphs.json (generated by design/build.py) because SVGs shown through
<img> on GitHub cannot load fonts. If the calendar cannot be read, the last good
artwork is left untouched; nothing is ever invented.
"""
from __future__ import annotations

import json
import re
import sys
from datetime import date, timedelta
from html.parser import HTMLParser
from pathlib import Path
from urllib.request import Request, urlopen

USERNAME = "Janshafin"
ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "assets" / "proof-of-work.svg"
GLYPHS = json.loads((ROOT / "scripts" / "glyphs.json").read_text())
PAPER, INK, GRAPH, HAIR = "#E6E9EC", "#1E2A86", "#59606E", "#B9C0CA"
MONTHS = ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"]


class CalendarParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.levels: dict[date, int] = {}

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        day, level = a.get("data-date"), a.get("data-level")
        if not day or level is None:
            return
        try:
            d, lv = date.fromisoformat(day), int(level)
        except ValueError:
            return
        if 0 <= lv <= 4:
            self.levels[d] = lv


def fetch():
    req = Request(f"https://github.com/users/{USERNAME}/contributions", headers={
        "User-Agent": "Mozilla/5.0 (profile artwork renderer)", "Accept": "text/html"})
    with urlopen(req, timeout=25) as r:
        html = r.read().decode("utf-8", "replace")
    p = CalendarParser()
    p.feed(html)
    if len(p.levels) < 200:
        raise RuntimeError(f"Parsed only {len(p.levels)} days; keeping the previous artwork.")
    m = re.search(r"([\d,]+)\s+contributions?\s+in the last year", html)
    total = m.group(1) if m else None
    return p.levels, total


def g(key, x, y):
    return f'<g transform="translate({x:.1f} {y:.1f})">{GLYPHS[key][0]}</g>'


def number(s, x, y):
    out = []
    for ch in s:
        out.append(g("d" + ch, x, y))
        x += GLYPHS["d" + ch][1]
    return "".join(out), x


def draw(levels, total):
    W, H = 1200, 400
    today = max(levels)
    days = [today - timedelta(days=i) for i in range(364, -1, -1)]
    x0, x1, base = 64, 1136, 300
    step = (x1 - x0) / (len(days) - 1)
    heights = {0: 0, 1: 22, 2: 46, 3: 74, 4: 108}
    b = [f'<rect width="{W}" height="{H}" fill="{PAPER}"/>',
         g("title", 64, 112), g("sub", 64, 150)]
    if total:
        n, end = number(total, 0, 0)
        tw = end
        lw = GLYPHS["contrib"][1]
        b.append(f'<g transform="translate({1136 - tw - 12 - lw:.1f} 112)">{n}</g>')
        b.append(g("contrib", 1136 - lw, 112))
    b.append(f'<path d="M{x0} {base}H{x1}" stroke="{HAIR}" stroke-width="1.5"/>')
    marks = []
    for i, d in enumerate(days):
        x = x0 + i * step
        lv = levels.get(d, 0)
        if lv == 0:
            marks.append(f'<rect x="{x - .9:.1f}" y="{base - 1.8}" width="1.8" height="1.8" fill="{GRAPH}"/>')
        else:
            hh = heights[lv]
            marks.append(f'<rect x="{x - 1.3:.1f}" y="{base - hh}" width="2.6" height="{hh}" fill="{INK}">'
                         f'<title>{d.isoformat()}: level {lv} of 4</title></rect>')
        if d.day == 1:
            marks.append(f'<path d="M{x:.1f} {base + 6}V{base + 16}" stroke="{GRAPH}" stroke-width="1.5"/>')
            marks.append(g(MONTHS[d.month - 1], x + 6, base + 34))
    b += marks
    b.append(g("note", 64, 376))
    label = (f"Proof of work: one mark per day of Jan Shafin's public GitHub contributions for the year "
             f"ending {today.isoformat()}" + (f", {total} contributions in total." if total else "."))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" '
            f'role="img" aria-label="{label}"><title>{label}</title>{"".join(b)}</svg>\n')


def main():
    try:
        levels, total = fetch()
    except Exception as e:  # keep the last real artwork
        print(f"Skipped: {e}", file=sys.stderr)
        return
    OUTPUT.write_text(draw(levels, total))
    print(f"Wrote {OUTPUT} ({len(levels)} days, total={total})")


if __name__ == "__main__":
    main()
